function composerIcon(button, name, paths, label) {
    if (button.querySelector(`.postmark-${name}-icon`)) return;
    const drawing = icon(`postmark-${name}-icon`, paths);
    drawing.dataset.postmarkUi = "";
    button.append(drawing);
    if (label && !button.hasAttribute("aria-label")) {
        button.setAttribute("aria-label", label);
        button.dataset.postmarkLabel = "";
    }
}


function dateNumber(date) {
    return Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000;
}

function anniversary(start, firstMessageTime) {
    const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(start.trim());
    if (start.trim() && !match) return null;
    const manual = match ? new Date(Number(match[1]), Number(match[2]) - 1, Number(match[3])) : null;
    if (manual && (manual.getFullYear() !== Number(match[1]) || manual.getMonth() !== Number(match[2]) - 1 || manual.getDate() !== Number(match[3]))) return "";
    const firstDay = manual ?? new Date(firstMessageTime);
    if (!Number.isFinite(firstDay.getTime())) return "";
    const elapsed = dateNumber(new Date()) - dateNumber(firstDay) + 1;
    return elapsed > 0 ? elapsed : null;
}


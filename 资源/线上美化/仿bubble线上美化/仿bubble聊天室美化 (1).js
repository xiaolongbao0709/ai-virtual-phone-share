    function decorateQuote(row, remark) {
        const quote = row.querySelector(':scope > .chat-msg-content-wrap > [data-ui^="bubble-"] > .chat-quote-message');
        const native = quote?.querySelector(":scope > .chat-quote-preview");
        if (!native) {
            quote?.querySelector(":scope > .postmark-quote-card")?.remove();
            return;
        }
        const assistant = row.dataset.role === "assistant";
        const label = assistant ? `${remark}的回复` : "的回复";
        const text = native.textContent.trim();
        let card = quote.querySelector(":scope > .postmark-quote-card");
        if (!card) {
            card = element("div", "postmark-quote-card");
            native.before(card);
        }
        native.classList.add("postmark-native-quote");
        if (card.dataset.preview === text && card.dataset.label === label) return;
        card.dataset.preview = text;
        card.dataset.label = label;
        const title = element("div", "postmark-quote-title");
        title.textContent = label;
        if (!assistant) title.prepend(element("span", "postmark-quote-user-name"));
        // Native quote previews store bilingual text as original | Chinese.
        // Keep unpaired pipes intact, including table and code previews.
        const lines = text.replace(/\\r\\n|\\n|\\r/g, "\n").split(/\r?\n/);
        const pairs = lines.map(line => {
            const parts = line.split("|").map(part => part.trim());
            return parts.length >= 2 && parts.length % 2 === 0 && parts.every(Boolean)
                && parts.every((part, index) => index % 2 === 0 || /[\u3400-\u9fff]/.test(part))
                ? parts : null;
        });
        const bilingual = !text.includes("```") && pairs.some(Boolean)
            && pairs.every((pair, index) => pair || !lines[index].includes("|"));
        const originalText = bilingual ? pairs.map((pair, index) => pair
            ? pair.filter((_, part) => part % 2 === 0).join(" | ") : lines[index]).join("\n") : text;
        const excerpt = element("div", "postmark-quote-excerpt");
        const original = element("span", "postmark-quote-original");
        original.textContent = originalText;
        excerpt.append(original);
        if (assistant && bilingual) {
            const translation = element("span", "postmark-quote-translation");
            translation.textContent = pairs.map((pair, index) => pair
                ? pair.filter((_, part) => part % 2 === 1).join(" | ") : lines[index]).join("\n");
            excerpt.append(element("br", "postmark-quote-break"), translation);
        }
        card.replaceChildren(title, excerpt);
    }


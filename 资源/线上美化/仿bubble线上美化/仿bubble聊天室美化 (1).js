    function markRequestRead(payload) {
        if (payload.preview || payload.sessionId !== sessionId || payload.purpose !== "chat"
            || !room.classList.contains(roomClass) || room.querySelector('button[aria-label="返回线上模式"]')) return payload;
        const messages = ctx.data.messages.list(sessionId);
        let changed = false;
        for (let index = messages.length - 1; index >= 0; index--) {
            const message = messages[index];
            if (message.role === "assistant") break;
            if (message.role !== "user" || message.status === "failed" || message.status === "sending" || readIds.has(message.id)) continue;
            readIds.add(message.id);
            changed = true;
        }
        if (changed) {
            while(readIds.size>1000)readIds.delete(readIds.values().next().value);
            // Presentation-only receipt: the chat request has entered processing.
            // Preserve native message delivery status and never run for prompt previews.
            ctx.system.storage.set(receiptKey, [...readIds].slice(-1000));
            fullRefresh = true;
            schedule();
        }
        return payload;
    }


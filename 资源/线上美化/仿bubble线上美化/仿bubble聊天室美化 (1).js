    function dismissMenu(event) {
        if ((event.type === "keydown" && event.key === "Escape") || (event.type === "pointerdown" && !event.target.closest?.(".postmark-offline-more,.postmark-offline-card-menu"))) {
            room.querySelectorAll(".postmark-offline-card-menu").forEach(menu => menu.remove());
            room.querySelectorAll('.postmark-offline-more[aria-expanded="true"]').forEach(button => button.setAttribute("aria-expanded", "false"));
        }
        if (offlineMenuOpen) {
            if (event.type === "keydown" && event.key !== "Escape") return;
            if (event.type === "pointerdown" && (toolsPanel.contains(event.target) || veil.contains(event.target) || room.querySelector(':scope > .page-header button[aria-label="更多"]')?.contains(event.target))) return;
            offlineMenuOpen = false; schedule(); return;
        }
        const bar = room.querySelector(":scope > .postmark-compact-composer");
        if (!bar?.querySelector(":scope > .postmark-quick-menu")) return;
        if (event.type === "keydown" && event.key !== "Escape") return;
        if (event.type === "pointerdown" && room.classList.contains("postmark-menu-top")
            && room.querySelector(':scope > .page-header button[aria-label="更多"]')?.contains(event.target)) return;
        if (event.type === "pointerdown" && (bar.contains(event.target) || toolsPanel.contains(event.target) || veil.contains(event.target))) return;
        const plus = bar.querySelector(".postmark-plus-icon")?.parentElement;
        plus?.click();
        if (event.type === "keydown") {
            event.preventDefault();
            plus?.focus();
        }
    }

    const observer = new MutationObserver(records => {
        let changed = false;
        for (const record of records) {
            const target = record.target instanceof Element ? record.target : record.target.parentElement;
            if (!target || target.closest("[data-postmark-ui]")) continue;
            if(record.type==='childList'){
                const changedNodes=[...record.addedNodes,...record.removedNodes];
                if(changedNodes.length&&changedNodes.every(node=>node instanceof Element&&node.hasAttribute('data-postmark-ui')))continue;
                if(changedNodes.some(node=>node instanceof Element))structureDirty=true;
            }
            const row = target.closest(messageSelector);
            if (row) dirty.add(row);
            for (const child of record.addedNodes) {
                if (!(child instanceof Element) || child.hasAttribute("data-postmark-ui")) continue;
                if (child.matches(messageSelector)) dirty.add(child);
                child.querySelectorAll(messageSelector).forEach(item => dirty.add(item));
            }
            changed = true;
        }
        if (changed) schedule();
    });
    observer.observe(room, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ["aria-expanded", "data-active", "disabled", "aria-label"] });
    search.addEventListener("click", openNativeSearch);
    document.addEventListener("pointerdown", dismissMenu, true);
    document.addEventListener("keydown", dismissMenu, true);
    room.addEventListener("click", captureCardAction, true);
    room.addEventListener("click", topMenuClick, true);
    window.addEventListener("focus", refreshFromOutside);
    window.addEventListener("resize", schedule);
    document.addEventListener("visibilitychange", refreshFromOutside);
    const subscriptions = [
        subscribeLocal(relay.requests, markRequestRead),
        subscribeLocal(relay.settings, () => { fullRefresh = true; schedule(); }),
        subscribeLocal(relay.persisted, ({ message }) => { if (message.sessionId === sessionId) messagesChanged(); }),
        subscribeLocal(relay.deleted, event => { if (event.sessionId === sessionId) messagesChanged(); }),
        subscribeLocal(relay.updated, ({ id }) => { if (messageMap?.has(id)) messagesChanged(); }),
    ];
    refresh();

    return () => {
        disposed=true;
        observer.disconnect();
        contentObserver.disconnect();
        endSearch();
        if (frame) window.cancelAnimationFrame(frame);
        window.clearTimeout(dayTimer);
        dateDialog?.close();
        subscriptions.forEach(unsubscribe => unsubscribe());
        search.removeEventListener("click", openNativeSearch);
        document.removeEventListener("pointerdown", dismissMenu, true);
        document.removeEventListener("keydown", dismissMenu, true);
        room.removeEventListener("click", topMenuClick, true);
        room.removeEventListener("click", captureCardAction, true);
        window.removeEventListener("focus", refreshFromOutside);
        window.removeEventListener("resize", schedule);
        document.removeEventListener("visibilitychange", refreshFromOutside);
        room.classList.remove(roomClass, "postmark-show-artist", "postmark-menu-top", "postmark-top-more");
        clearRows();
    };
